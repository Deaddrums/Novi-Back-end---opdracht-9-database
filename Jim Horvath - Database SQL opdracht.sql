-- User_Role junction table

CREATE TABLE user_role (
    user_id INT NOT NULL,
    roles_id INT NOT NULL,

    PRIMARY KEY (user_id, roles_id),

    FOREIGN KEY (user_id) REFERENCES users(id),
    FOREIGN KEY (roles_id) REFERENCES roles(id)
);

INSERT INTO user_role (user_id, roles_id)
VALUES
    (1, 1),
    (1, 2),
    (2, 1),
    (3, 1);

SELECT
    users.username,
    roles.rolename
FROM user_role
JOIN users ON user_role.user_id = users.id
JOIN roles ON user_role.roles_id = roles.id;


-- Album table 

CREATE TABLE album (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    release_year INT NOT NULL,
    publisher_id INT NOT NULL,
    genre_id INT NOT NULL,

    FOREIGN KEY (publisher_id) REFERENCES publisher(id),
    FOREIGN KEY (genre_id) REFERENCES genre(id)
);

INSERT INTO album (title, release_year, publisher_id, genre_id)
VALUES 
    ('Adultery', 1999, 1, 3),
    ('Too fast too die', 2026, 1, 1),
    ('Chaosphere', 1995, 2, 2);

SELECT
    album.title,
    album.release_year,
    publisher.name AS publisher,
    genre.name AS genre
FROM album
JOIN publisher ON album.publisher_id = publisher.id
JOIN genre ON album.genre_id = genre.id;

-- Stock table
create table stock (
	id int generated by default as identity primary key,
	condition varchar (255) not null, 
	price decimal(10, 2) not null,
	album_id int not null,

	foreign key (album_id) references album(id)
);

INSERT INTO stock (condition, price, album_id)
VALUES
    ('New', 24.99, 1),
    ('Used', 14.99, 1),
    ('New', 29.99, 2),
    ('Good', 19.99, 3);

SELECT
    album.title,
    stock.condition,
    stock.price
FROM stock
JOIN album ON stock.album_id = album.id;

-- album cover table
CREATE TABLE album_cover (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    picture_data TEXT,
    description TEXT,
    content_type VARCHAR(255),
    file_name VARCHAR(255),
    album_id INT NOT NULL UNIQUE,

    FOREIGN KEY (album_id) REFERENCES album(id)
);

